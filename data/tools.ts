export function getToolByRoute(route: string): ToolMetadata | undefined {
  return TOOLS.find((t) => t.route === route)
}

export function getToolsByCategory(category: ToolCategory): ToolMetadata[] {
  return TOOLS.filter((t) => t.category === category)
}

export function getPopularTools(): ToolMetadata[] {
  return TOOLS.filter((t) => t.popular)
}

export function getRelatedTools(currentToolId: string, limit: number = 4): ToolMetadata[] {
  const current = TOOLS.find((t) => t.id === currentToolId)
  if (!current) return TOOLS.slice(0, limit)

  // Prioritize same category, then popular
  const sameCategory = TOOLS.filter((t) => t.category === current.category && t.id !== currentToolId)
  if (sameCategory.length >= limit) {
    return sameCategory.slice(0, limit)
  }

  const others = TOOLS.filter((t) => t.id !== currentToolId && t.category !== current.category)
  return [...sameCategory, ...others].slice(0, limit)
}
